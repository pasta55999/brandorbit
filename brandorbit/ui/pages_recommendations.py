from __future__ import annotations

import pandas as pd
import streamlit as st

from brandorbit.analysis.recommendations import generate_findings
from brandorbit.core.schemas import FindingStatus, Severity
from brandorbit.monitoring.runner import RunLimitError, run_monitoring
from brandorbit.providers import available_providers, first_live_provider
from brandorbit.ui.common import demo_banner, get_repo, page_header, quote, select_run, select_workspace, severity_badge, settings, short_pid

SEV_ORDER = {Severity.high: 0, Severity.medium: 1, Severity.low: 2}


def render() -> None:
    repo = get_repo()
    ws = select_workspace(repo)
    run = select_run(repo, ws)
    page_header("Recommendations", "Prioritised issues with evidence, a proposed action and an expected outcome stated as a hypothesis.")
    demo_banner(ws, run)
    if run is None:
        st.info("No runs yet.")
        return
    findings = repo.list_findings(ws.id, run.id)
    top = st.columns([2, 2, 2, 3])
    sev_f = top[0].multiselect("Severity", [s.value for s in Severity], default=[s.value for s in Severity])
    stat_f = top[1].multiselect("Status", [s.value for s in FindingStatus], default=["open", "planned"])
    cat_f = top[2].multiselect("Category", sorted({f.category for f in findings}))
    with top[3]:
        st.write("")
        use_llm = st.checkbox("Enrich wording with LLM", value=False, help="Uses a live provider to rewrite explanations. Output is schema-validated and may only reuse existing evidence quotes. Unavailable in demo mode.", disabled=settings().demo_mode)
        if st.button("Regenerate findings for this run", use_container_width=True):
            narrator = first_live_provider() if use_llm else None
            generate_findings(repo, ws, run.id, narrator=narrator)
            st.rerun()

    shown = sorted([f for f in findings if f.severity.value in sev_f and f.status.value in stat_f and (not cat_f or f.category in cat_f)], key=lambda f: (SEV_ORDER[f.severity], f.finding_id))
    if not findings:
        st.info("No findings stored for this run. Click 'Regenerate findings'.")
        return
    st.caption(f"{len(shown)} of {len(findings)} findings shown. Generated by deterministic rules over stored extractions"
               + ("; LLM narration enabled." if any(f.generated_by == 'rules+llm' for f in findings) else ". LLM narration not used."))
    pmap = {p.id: p for p in repo.list_prompts(ws.id)}
    for f in shown:
        with st.container(border=True):
            h1, h2 = st.columns([6, 2])
            h1.markdown(f"{severity_badge(f.severity.value)} &nbsp; **{f.finding_id}** - {f.title}", unsafe_allow_html=True)
            h2.markdown(f"<div style='text-align:right'><code>{f.category}</code> - {f.verification_status.value} - conf. {f.confidence:.0%}</div>", unsafe_allow_html=True)
            st.markdown(f"**Why it matters.** {f.explanation}")
            st.markdown(f"**Proposed action.** {f.proposed_action}")
            st.markdown(f"**Expected outcome (hypothesis).** {f.expected_outcome}")
            if f.limitations:
                st.caption(f"Limitations: {f.limitations}")
            with st.expander(f"Why was this generated? Evidence ({len(f.evidence)})"):
                st.caption(f"Rule: `{f.category}` - generated_by `{f.generated_by}` - related prompts: {', '.join(short_pid(p) for p in f.related_prompt_ids) or '-'}")
                for e in f.evidence:
                    p = pmap.get(e.prompt_id)
                    st.markdown(f"- Prompt `{short_pid(e.prompt_id)}`: _{p.text if p else ''}_ - response `{e.response_id}`" + (f" - source: {e.source_url}" if e.source_url else ""))
                    quote(e.quote)
                if f.source_url:
                    st.markdown(f"Source URL: {f.source_url}")
            a1, a2, a3 = st.columns([2, 2, 3])
            new_status = a1.selectbox("Status", [s.value for s in FindingStatus], index=[s.value for s in FindingStatus].index(f.status.value), key=f"st_{f.id}", label_visibility="collapsed")
            if new_status != f.status.value:
                repo.update_finding_status(f.id, FindingStatus(new_status))
                st.rerun()
            if f.related_prompt_ids and a2.button("Re-run related prompts", key=f"rr_{f.id}", help="Runs only the prompts linked to this finding on the selected providers and stores a new run."):
                _rerun_prompts(repo, ws, f.related_prompt_ids, f.finding_id)
            a3.caption(f"Created {f.created_at:%Y-%m-%d}. Recommendations are advisory - BrandOrbit never changes external systems.")


def _rerun_prompts(repo, ws, prompt_ids: list[str], finding_id: str) -> None:
    provs = available_providers()
    live = [p for p in provs.values() if p.is_live]
    chosen = live or [p for p in provs.values()]
    prompts = [p for p in repo.list_prompts(ws.id) if p.id in prompt_ids]
    try:
        with st.spinner("Running prompts..."):
            run = run_monitoring(repo, ws, chosen, prompts=prompts, label=f"Re-check for {finding_id}", notes=f"Partial re-run of prompts linked to {finding_id}")
        st.success(f"Stored run '{run.label}' ({run.status}). Select it in the sidebar to inspect, or compare it in 'Compare runs'. "
                   + ("Demo providers replay fixture answers, so results will mirror the fixture run." if not live else ""))
    except RunLimitError as exc:
        st.error(str(exc))
